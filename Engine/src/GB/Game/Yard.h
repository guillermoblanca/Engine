#pragma once
// PROTOTYPE of documentation/01_diseno/TALLERES.md section 10 (D89: yards and modules), 2026-11-20. The yard of a house is not saved: it is worked
// out from the house's footprint, its yard block (BuildingDef::Yard), where it stands and its turn, by this pure function. It gives the fence (a
// rounded rectangle with its gate on the side of the door, +z of the building, cut into posts and rails) and the slots where modules stand, each
// with its work point (`Use` = slot + front x reach; who works there faces -front). The same input always gives the same yard.
//
// The numbers that are not the house's (the reach and inset of each kind of slot, the fence's posts and rails) are data: the "yards" section of
// assets/data/yards.json (DefaultYardRules). CPU only, deterministic, headless.
#include "GB/Gameplay/Buildings.h"
#include <glm/glm.hpp>
#include <map>
#include <string>
#include <vector>

namespace GB
{
	struct YardSlotKind
	{
		float Reach = 0.85f;   // metres from the slot's centre to where its worker stands
		float Inset = 1.0f;    // metres in from the fence (corner, gate, wall) or out from the house's wall (lean_to)
	};

	// The look of the fence, generated by code from these numbers (no model): a post every ~PostSpacing metres, taller posts at the gate, and
	// a rail between two posts at each height of Rails.
	struct YardFenceLook
	{
		float PostSpacing = 1.7f, PostHeight = 1.0f, PostWidth = 0.11f, GatePostHeight = 1.6f, GatePostWidth = 0.16f, RailWidth = 0.06f;
		std::vector<float> Rails{ 0.45f, 0.86f };
		glm::vec3 PostColor{ 0.34f, 0.25f, 0.16f }, RailColor{ 0.5f, 0.4f, 0.27f };
	};

	struct YardRules
	{
		std::map<std::string, YardSlotKind> SlotKinds;   // "corner", "gate", "wall", "lean_to"
		YardFenceLook Fence;
	};

	// The "yards" section (assets/data/yards.json) over `rules`: "" or why it is wrong (then nothing changed).
	std::string LoadYardRules(const std::string& json, YardRules& rules);
	// The section as the game's data ships it (read once).
	const YardRules& DefaultYardRules();

	struct YardSlot
	{
		std::string Id;        // "corner_FL", "gate_R", "wall_E0", "house_W0"
		std::string Kind;      // "corner", "gate", "wall", "lean_to"
		glm::vec2 Pos{ 0.0f };     // its centre on the ground (world x, z)
		glm::vec2 Front{ 0.0f, 1.0f };   // towards its worker (unit, world)
		glm::vec2 Use{ 0.0f };     // where its worker stands
		float Yaw = 0.0f;          // degrees (as Transform.Rotation.y) that turn a building's +z (its front) to Front
	};

	struct YardShape
	{
		bool Valid = false;
		std::vector<glm::vec2> Outline;   // the fence's line, closed (the gate included), world x, z
		std::vector<glm::vec2> Posts;     // from one side of the gate round to the other: the first and the last are the gate's posts
		glm::vec2 GateL{ 0.0f }, GateR{ 0.0f };
		float Length = 0.0f;              // metres of fence (the gate left out)
		std::vector<YardSlot> Slots;
	};

	// The yard of a house `host` standing at `pos` turned `yawDegrees` (empty when the building has no yard block).
	YardShape ComputeYard(const BuildingDef& host, const glm::vec2& pos, float yawDegrees, const YardRules& rules);
}
